export const detectLang = () => {
  try {
    const l = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2);
    return LANGS.includes(l) ? l : 'es';
  } catch { return 'es'; }
};

// El idioma de la interfaz define el formato de números y fechas; la moneda la define el país del trabajo.
let locale = 'es';
export const setLocale = (l) => { locale = l; };

export const money = (v, cur) => {
  try { return new Intl.NumberFormat(locale, { style: 'currency', currency: cur }).format(Number(v)); }
  catch { return `${v} ${cur}`; }
};

export const fmtDate = (d) => {
  try { return new Intl.DateTimeFormat(locale, { dateStyle: 'medium' }).format(new Date(`${String(d).slice(0, 10)}T12:00:00`)); }
  catch { return d; }
};
